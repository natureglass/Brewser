// Khronos tests routinely fire-and-forget async functions (`runFoo();`
// where runFoo is async). When such a function throws — e.g.,
// `ReferenceError: wtu is not defined` from a helper script that
// expected `wtu` to be a global — the rejection is unhandled. nx.js's
// default unhandled-rejection handler calls `$.print` (the same path
// as `console.error`), which flips the runtime into text-render mode —
// see [[console-error-switches-render-mode]] — freezing the canvas and
// halting the shell's rAF tick chain. Once that happens our heartbeat
// stops, main()'s nextFrame awaits never resolve, and the runner is
// dead in the water. Install handlers across all the global hooks
// QuickJS / nx.js / browser-shim might surface so we swallow these
// rejections silently. Diagnosed 2026-05-23 while bringing up
// attribs-gl-enable-vertex-attrib (test #6).
globalThis.onunhandledrejection = function (event) {
	if (event && typeof event.preventDefault === 'function') event.preventDefault();
	return true;
};
