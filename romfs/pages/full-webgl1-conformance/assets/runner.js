async function main() {
	diag('main() entered');
	UI.state = 'idle';
	safeRenderStatus('main-entry');
	diag('main() about to await first nextFrame');
	await nextFrame();
	diag('main() past first nextFrame');

	let testList;
	try {
		// Read tests.json directly via Switch.readFileSync — bypasses
		// runtime-fetch + BrowserResourceLoader entirely. Diagnosed
		// 2026-05-23: fetch('browser://...') from a detached promise
		// hangs silently on Citron for our runner page (the await never
		// resolves). Synchronous reads are reliable and we yield
		// cooperatively via rAF between tests.
		diag('main() about to readTextSync tests.json (romfs)');
		const text = readTextSync('romfs:/pages/full-webgl1-conformance/assets/tests.json');
		const json = JSON.parse(text);
		testList = json.tests || [];
		diag('main() tests.json parsed; testCount=' + testList.length);
	} catch (e) {
		UI.currentName = 'tests.json read fail: ' + (e && e.message ? e.message : e);
		UI.state = 'aborted';
		safeRenderStatus('tests.json-fail');
		diag('main() tests.json read failed: ' + (e && e.message ? e.message : e));
		return;
	}

	UI.totalTests = testList.length;
	summaryHeader =
		'# full-webgl1-conformance summary\n' +
		'# generated: ' + new Date().toISOString() + '\n' +
		'# total: ' + testList.length + '\n';
	diag('main() about to rewriteSummary (initial)');
	rewriteSummary();
	diag('main() rewriteSummary done');
	if (safeRenderStatus('main-renderStatus#2')) {
		diag('main() renderStatus #2 done');
	}
	try {
		await nextFrame();
		diag('main() nextFrame #2 returned');
	} catch (e) {
		diag('main() nextFrame #2 THREW: ' + (e && e.message ? e.message : e));
	}
	diag('main() about to waitForStart(5000)');

	try {
		await waitForStart(5000);
		diag('main() waitForStart returned; entering run loop');
	} catch (e) {
		diag('main() waitForStart THREW: ' + (e && e.message ? e.message : e));
	}
	UI.state = 'running';
	diag('main() UI.state=running, starting test loop');

	const REWRITE_EVERY = 25;

	for (let i = 0; i < testList.length; i++) {
		if (!runnerActive) {
			diag('main() test loop bailing — runnerActive=false (page unloading)');
			return;
		}
		const test = testList[i];
		UI.currentIndex = i;
		// Render only every 5 tests in the loop — the heartbeat already
		// paints per rAF tick, so the test loop's own renderStatus is
		// just a top-up. Reducing call frequency limits exposure to the
		// FreeType resource leak (see safeRenderStatus comment above)
		// and saves a few ms per test.
		if (i % 5 === 0) safeRenderStatus('test-loop-iter-' + i);
		await nextFrame();

		const testUrl =
			'romfs:/pages/full-webgl1-conformance/sdk/tests/conformance/' + test.rel;

		// Write a tiny "currently running" tracker file BEFORE every
		// test. When the runner freezes mid-eval, the user can read
		// this file to know exactly which test hung — even when the
		// per-test log dir + summary log don't reflect it because the
		// hang happened before finalizeTest could write them.
		try {
			Switch.writeFileSync(SDMC_DIR + 'current-test.txt',
				'#' + i + ' / ' + testList.length + '\n' +
				test.name + '\n' +
				test.rel + '\n' +
				'started at ' + new Date().toISOString() + '\n');
		} catch (_) {}

		// Skip tests in the SKIP_TESTS set (built-in + user-extended).
		// Record as SKIP in the summary so we can see what we bypassed.
		if (SKIP_TESTS.has(test.name)) {
			diag('test #' + i + ' SKIPPED (skip list): ' + test.name);
			UI.timedOut++;  // count toward "timeouts" bucket visually
			UI.skipped++;   // also track separately for done-state breakdown
			pushRecent({ name: test.name, status: 'SKIP',
				passN: 0, failN: 0, ms: 0 });
			summaryLines.push(test.name + '\tSKIP\t0\t0\t0');
			continue;
		}

		// Per-test diag entries, rate-limited so we don't flood the
		// SDMC log on the long tail of fast-running tests. First 30
		// always logged so a hang in the early tests is fully traceable.
		const shouldDiag = (i < 30) || (i % 25 === 0);
		if (shouldDiag) diag('test #' + i + ' START: ' + test.name);

		try {
			await runOneTest(test, testUrl);
			if (shouldDiag) diag('test #' + i + ' END: status=' +
				(harnessState.failCount === 0 && harnessState.finished ? 'PASS' :
					(harnessState.finished ? 'FAIL' : 'TIMEOUT/ERROR')) +
				' p=' + harnessState.passCount + ' f=' + harnessState.failCount);
		} catch (e) {
			const elapsed = Date.now() - harnessState.startMs;
			UI.errored++;
			pushRecent({ name: test.name, status: 'ERROR',
				passN: harnessState.passCount, failN: harnessState.failCount,
				ms: elapsed });
			summaryLines.push(test.name + '\tERROR\t' +
				harnessState.passCount + '\t' + harnessState.failCount + '\t' + elapsed);
			cleanupTestResources();
			clearTestShims();
			diag('test #' + i + ' CRASHED: ' + (e && e.message ? e.message : e));
		}

		const pads = gamepadState();
		if (pads && pads.PLUS) {
			UI.state = 'aborted';
			UI.currentIndex = i + 1;
			safeRenderStatus('aborted');
			rewriteSummary();
			diag('test loop aborted by user at test #' + i);
			return;
		}

		if ((i + 1) % REWRITE_EVERY === 0) {
			rewriteSummary();
			diag('summary rewritten at test #' + (i + 1));
		}

		// Periodic GC + yield to ease cumulative resource pressure.
		// The shared screen-GL context accumulates programs/textures/
		// buffers across all tests (we don't track per-test resources
		// to delete them explicitly), and after ~150-200 tests this
		// makes individual tests start hanging that completed quickly
		// earlier. nx.js may not expose globalThis.gc — try anyway,
		// best-effort.
		if ((i + 1) % 25 === 0) {
			try { if (typeof globalThis.gc === 'function') globalThis.gc(); } catch (_) {}
			// Two extra rAF yields to let the runtime breathe.
			await nextFrame();
			await nextFrame();
		}
	}

	UI.state = 'done';
	UI.currentIndex = testList.length;
	UI.currentName = '';
	UI.currentUrl = '';
	rewriteSummary();
	safeRenderStatus('done');
	diag('main() test loop COMPLETE — all ' + testList.length + ' tests processed');
}

