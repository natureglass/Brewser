function parseAttrs(attrStr) {
	const out = {};
	const re = /([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/g;
	let m;
	while ((m = re.exec(attrStr)) !== null) {
		out[m[1].toLowerCase()] = m[2] !== undefined ? m[2] : (m[3] !== undefined ? m[3] : m[4]);
	}
	return out;
}

function isJsType(type) {
	if (!type) return true;
	return /^(text|application)\/(java|ecma)script$/i.test(type);
}

function parseTestHtml(html) {
	// Strip comments so commented-out scripts don't confuse the scanner.
	const cleaned = html.replace(/<!--[\s\S]*?-->/g, '');

	const canvases = [];
	const canvasRe = /<canvas\b([^>]*)>/gi;
	let cm;
	while ((cm = canvasRe.exec(cleaned)) !== null) {
		const a = parseAttrs(cm[1]);
		canvases.push({
			id: a.id || '',
			width: parseInt(a.width || '300', 10) || 300,
			height: parseInt(a.height || '150', 10) || 150,
		});
	}

	const externalScripts = [];
	const shaderScripts = []; // { id, type, text }
	const inlineBodies = [];

	const scriptRe = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
	let m;
	while ((m = scriptRe.exec(cleaned)) !== null) {
		const a = parseAttrs(m[1]);
		const body = m[2];
		if (a.src) {
			externalScripts.push({ src: a.src, type: a.type || '' });
		} else if (a.id && !isJsType(a.type)) {
			// Shader block (or other non-JS script with an id).
			shaderScripts.push({ id: a.id, type: a.type || '', text: body });
		} else if (isJsType(a.type)) {
			inlineBodies.push(body);
		}
		// Non-JS-typed scripts without an id are ignored.
	}

	return { canvases, externalScripts, shaderScripts, inlineBodies };
}

