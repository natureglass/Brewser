// `readTextSync` is defined near the top of this file (alongside `diag`)
// because the wtu init block needs to call it at script-body parse time.
// We use it in place of `fetch(...)` for all internal reads (tests.json,
// per-test HTML, helper JS) because the runtime-fetch chain has been
// observed to hang silently on Citron for browser:// URLs from inside a
// detached promise — diagnosed via runner-diag.log showing the await
// past `fetch('browser://...')` never resolves. Switch.readFileSync is
// synchronous + reliable; we cooperatively yield to rAF between tests.

function loadAndExecuteScriptSync(url) {
	const text = readTextSync(url);
	(0, eval)(text);
}

async function runOneTest(test, testUrl) {
	const verbose = test.name === 'attribs-gl-enable-vertex-attrib' ||
		test.name === 'attribs-gl-disabled-vertex-attrib';
	if (verbose) diag('  ROT: resetGLState start [' + test.name + ']');
	resetGLState();
	if (verbose) diag('  ROT: resetGLState done');
	resetHarness(test.name);
	UI.currentName = test.name;
	UI.currentUrl = testUrl;

	let htmlText;
	try {
		if (verbose) diag('  ROT: readTextSync ' + testUrl);
		htmlText = readTextSync(testUrl);
		if (verbose) diag('  ROT: readTextSync done, bytes=' + htmlText.length);
	} catch (e) {
		harnessState.uncaughtError = 'read failed: ' + (e && e.message ? e.message : e);
		return finalizeTest(test, 'ERROR');
	}

	let parsed;
	try {
		parsed = parseTestHtml(htmlText);
		if (verbose) diag('  ROT: parsed; scripts=' + parsed.externalScripts.length +
			' shaders=' + parsed.shaderScripts.length +
			' inlines=' + parsed.inlineBodies.length);
	} catch (e) {
		harnessState.uncaughtError = 'parse failed: ' + (e && e.message ? e.message : e);
		return finalizeTest(test, 'ERROR');
	}

	installTestShims(parsed);
	if (verbose) diag('  ROT: shims installed');

	// Pre-load any external scripts the test depends on (other than the
	// ones we skip because the harness above replaces them).
	for (const ext of parsed.externalScripts) {
		const resolved = resolveUrl(ext.src, testUrl);
		if (shouldSkipScript(resolved)) {
			if (verbose) diag('  ROT: SKIP ext=' + resolved);
			continue;
		}
		try {
			if (verbose) diag('  ROT: LOAD ext=' + resolved);
			loadAndExecuteScriptSync(resolved);
			if (verbose) diag('  ROT: LOAD done ' + resolved);
		} catch (e) {
			// Surface in the per-test log so a "function not defined"
			// failure later in the test body is traceable back to the
			// helper script that didn't load.
			appendLog('  WARN: external script load failed: ' + resolved +
				' — ' + (e && e.message ? e.message : e));
			if (verbose) diag('  ROT: LOAD FAILED ' + resolved + ': ' +
				(e && e.message ? e.message : e));
		}
	}

	const combinedBody = parsed.inlineBodies.join('\n;\n');
	if (verbose) diag('  ROT: about to eval body, length=' + combinedBody.length);

	let evalError = null;
	try {
		(0, eval)(combinedBody);
		if (verbose) diag('  ROT: eval body returned (no sync throw)');
	} catch (e) {
		evalError = e;
		if (verbose) diag('  ROT: eval body THREW: ' + (e && e.message ? e.message : e));
	}

	// Give async / rAF-deferred tests a few ticks to finish.
	for (let i = 0; i < 5 && !harnessState.finished; i++) {
		if (verbose) diag('  ROT: grace tick ' + i);
		await nextFrame();
	}
	if (verbose) diag('  ROT: grace done, finished=' + harnessState.finished);

	let status;
	if (harnessState.finished) {
		status = harnessState.failCount === 0 ? 'PASS' : 'FAIL';
	} else if (evalError) {
		harnessState.uncaughtError = 'uncaught: ' +
			(evalError && evalError.message ? evalError.message : evalError);
		globalThis.testFailed(harnessState.uncaughtError);
		globalThis.finishTest();
		status = 'ERROR';
	} else {
		globalThis.testFailed('test never called finishTest()');
		globalThis.finishTest();
		status = 'TIMEOUT';
	}

	return finalizeTest(test, status);
}

function finalizeTest(test, status) {
	const elapsed = Date.now() - harnessState.startMs;
	const passN = harnessState.passCount;
	const failN = harnessState.failCount;
	if (status === 'PASS') UI.passed++;
	else if (status === 'FAIL') UI.failed++;
	else if (status === 'TIMEOUT') UI.timedOut++;
	else UI.errored++;

	// Accumulate assertion-level tallies for the headline pass-rate metric.
	// We add for every status (including TIMEOUT / ERROR / FAIL) because
	// even tests that didn't reach finishTest() typically ran tens or
	// hundreds of real assertions before getting stuck.
	UI.assertPassed += passN;
	UI.assertFailed += failN;

	const recent = { name: test.name, status, passN, failN, ms: elapsed };
	pushRecent(recent);

	summaryLines.push(test.name + '\t' + status + '\t' + passN + '\t' + failN + '\t' + elapsed);

	writePerTestLog(test.name, status, harnessState.log);

	// Phase 2: delete every WebGL resource this test created. Without
	// this the shared screen-GL context's program/shader/buffer/texture/
	// FBO/renderbuffer pools accumulate across all 745 tests, and the
	// pressure causes a cluster of "resource-flake" tests to start
	// hanging the JS thread at test 167+ in earlier runs. Cleanup is
	// best-effort and silent; any per-delete throw is swallowed.
	cleanupTestResources();

	clearTestShims();

	return recent;
}

