// Truncate the diag log once at startup so each run starts fresh,
// then append every subsequent line. The legacy implementation kept
// every line in memory and rewrote the whole file on every call,
// which degraded to O(n^2) and stalled the runner around test #670
// once the diag log + per-test logs saturated the SDMC write path.
// Switch.appendFileSync (added 2026-05-23) keeps each diag write O(line).
try { Switch.writeFileSync(DIAG_PATH_EARLY, ''); } catch (_) {}
