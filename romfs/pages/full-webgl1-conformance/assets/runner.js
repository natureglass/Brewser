wtu.replaceParams = function (str /*, ...lookups */) {
	const args = arguments;
	return str.replace(/\$\(([^)]+)\)/g, function (_, key) {
		for (let i = 1; i < args.length; i++) {
			if (args[i][key] !== undefined) return args[i][key];
		}
		throw new Error('unknown replaceParams key: ' + key);
	});
};

wtu.glEnumToString = function (gl, value) {
	if (!gl.__enumNameCache) {
		const cache = {};
		for (const k in gl) {
			try {
				const v = gl[k];
				if (typeof v === 'number' && /^[A-Z][A-Z0-9_]*$/.test(k) && cache[v] === undefined) {
					cache[v] = k;
				}
			} catch (_) { /* skip getter that throws */ }
		}
		Object.defineProperty(gl, '__enumNameCache', { value: cache, enumerable: false });
	}
	return gl.__enumNameCache[value] || ('0x' + (value >>> 0).toString(16));
};

wtu.create3DContext = function (elementOrId, attribs, version) {
	const canvas = (typeof elementOrId === 'string')
		? globalThis.document.getElementById(elementOrId)
		: (elementOrId || globalThis.document.getElementById('webgl-canvas'));
	if (!canvas) { globalThis.testFailed('canvas element not found: ' + elementOrId); return null; }
	const kind = (version === 2) ? 'webgl2' : 'webgl';
	const gl = canvas.getContext(kind, attribs || {});
	if (!gl) { globalThis.testFailed('getContext("' + kind + '") returned null'); return null; }
	if (typeof gl.enableGpuBridgePrototype === 'function') {
		try { gl.enableGpuBridgePrototype(true); } catch (_) {}
	}
	// Drain inherited error state. Cap at 100 to prevent infinite loops
	// when the runtime returns a persistent error code (some bridge
	// states can't be cleared by getError alone) — without the cap, a
	// single bad-state test deadlocks the whole runner.
	let drains = 0;
	while (drains < 100 && gl.getError() !== gl.NO_ERROR) drains++;
	return gl;
};

