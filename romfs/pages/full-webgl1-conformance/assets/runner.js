// Acquire the shared screen GL early so we can reset state between
// tests without waiting for the first test to acquire it. Must NOT be
// hoisted to the top of the file — see the note near the diag setup
// for why earlier acquisition disturbs rAF timing.
const bootGl = webglCanvasShim.getContext('webgl');

function drainGlErrors(gl, max) {
	let n = 0;
	while (n < (max || 100) && gl.getError() !== gl.NO_ERROR) n++;
	return n;
}

// ============================================================
// Per-test WebGL resource tracking (Phase 2)
// ============================================================
//
// The shared screen GL context is reused across every test we run, and
// tests typically never delete the programs/shaders/buffers/textures/
// FBOs/renderbuffers they create. After ~150 tests the cumulative GPU
// memory + shader-cache pressure causes resource-flake tests to start
// hanging (the very same tests that completed in 50ms early in the
// run start hanging at test 167+).
//
// Mitigation: monkey-patch the gl.create* functions to push each newly-
// created resource into a per-test array. After each test finalizes,
// call the matching gl.delete* on every tracked resource. This makes
// each test see roughly the same baseline GL state regardless of what
// the previous test allocated.
//
// We patch on `bootGl` directly. Because the runtime returns the same
// shared screen GL context for every `canvas.getContext('webgl')` call
// (see [[swb-webgl-inline]]), every test's `gl` object IS this same
// `bootGl`, so the patch covers every test transparently.

const trackedResources = {
	programs: [],
	shaders: [],
	buffers: [],
	textures: [],
	framebuffers: [],
	renderbuffers: [],
};

function patchCreate(gl, createName, arrayName) {
	if (!gl || typeof gl[createName] !== 'function') return;
	const orig = gl[createName];
	gl[createName] = function () {
		const result = orig.apply(this, arguments);
		if (result) trackedResources[arrayName].push(result);
		return result;
	};
}

if (bootGl) {
	patchCreate(bootGl, 'createProgram', 'programs');
	patchCreate(bootGl, 'createShader', 'shaders');
	patchCreate(bootGl, 'createBuffer', 'buffers');
	patchCreate(bootGl, 'createTexture', 'textures');
	patchCreate(bootGl, 'createFramebuffer', 'framebuffers');
	patchCreate(bootGl, 'createRenderbuffer', 'renderbuffers');
	diag('per-test GL resource tracking installed on bootGl');
}

function cleanupTestResources() {
	const gl = bootGl;
	if (!gl) return;
	// Unbind anything currently bound before deleting — calling
	// `deleteBuffer` on the bound ARRAY_BUFFER auto-unbinds it (per
	// spec), but unbinding explicitly first makes the deletes pure
	// reclaim operations.
	try {
		gl.useProgram(null);
		gl.bindBuffer(gl.ARRAY_BUFFER, null);
		gl.bindBuffer(gl.ELEMENT_ARRAY_BUFFER, null);
		gl.bindTexture(gl.TEXTURE_2D, null);
		gl.bindTexture(gl.TEXTURE_CUBE_MAP, null);
		if (gl.bindFramebuffer) gl.bindFramebuffer(gl.FRAMEBUFFER, null);
		if (gl.bindRenderbuffer) gl.bindRenderbuffer(gl.RENDERBUFFER, null);
	} catch (_) {}
	let counts = {};
	try {
		for (const p of trackedResources.programs) {
			try { gl.deleteProgram(p); } catch (_) {}
		}
		counts.programs = trackedResources.programs.length;
		for (const s of trackedResources.shaders) {
			try { gl.deleteShader(s); } catch (_) {}
		}
		counts.shaders = trackedResources.shaders.length;
		for (const b of trackedResources.buffers) {
			try { gl.deleteBuffer(b); } catch (_) {}
		}
		counts.buffers = trackedResources.buffers.length;
		for (const t of trackedResources.textures) {
			try { gl.deleteTexture(t); } catch (_) {}
		}
		counts.textures = trackedResources.textures.length;
		for (const f of trackedResources.framebuffers) {
			try { gl.deleteFramebuffer(f); } catch (_) {}
		}
		counts.framebuffers = trackedResources.framebuffers.length;
		for (const r of trackedResources.renderbuffers) {
			try { gl.deleteRenderbuffer(r); } catch (_) {}
		}
		counts.renderbuffers = trackedResources.renderbuffers.length;
	} catch (e) {
		realConsoleDebug('[runner] cleanupTestResources threw', e);
	}
	// Empty the arrays for the next test.
	trackedResources.programs.length = 0;
	trackedResources.shaders.length = 0;
	trackedResources.buffers.length = 0;
	trackedResources.textures.length = 0;
	trackedResources.framebuffers.length = 0;
	trackedResources.renderbuffers.length = 0;
	// Flush pending ops + drain errors generated by the delete sequence.
	// `flush()` is cheaper than `finish()` (it just submits to the GPU
	// queue; doesn't wait for completion). Per-test latency matters more
	// than per-test memory pressure since the cleanup itself is the
	// main lever for pressure relief.
	try { if (typeof gl.flush === 'function') gl.flush(); } catch (_) {}
	drainGlErrors(gl);
	return counts;
}

function resetGLState() {
	const gl = bootGl;
	if (!gl) return;
	try {
		drainGlErrors(gl);
		gl.useProgram(null);
		gl.bindBuffer(gl.ARRAY_BUFFER, null);
		gl.bindBuffer(gl.ELEMENT_ARRAY_BUFFER, null);
		gl.bindTexture(gl.TEXTURE_2D, null);
		gl.bindTexture(gl.TEXTURE_CUBE_MAP, null);
		if (gl.bindFramebuffer) gl.bindFramebuffer(gl.FRAMEBUFFER, null);
		if (gl.bindRenderbuffer) gl.bindRenderbuffer(gl.RENDERBUFFER, null);
		gl.disable(gl.SCISSOR_TEST);
		gl.disable(gl.DEPTH_TEST);
		gl.disable(gl.BLEND);
		gl.disable(gl.CULL_FACE);
		gl.disable(gl.STENCIL_TEST);
		gl.disable(gl.POLYGON_OFFSET_FILL);
		gl.disable(gl.SAMPLE_ALPHA_TO_COVERAGE);
		gl.disable(gl.SAMPLE_COVERAGE);
		gl.enable(gl.DITHER); // ES 2.0 default
		gl.depthFunc(gl.LESS);
		gl.depthMask(true);
		gl.colorMask(true, true, true, true);
		gl.cullFace(gl.BACK);
		gl.frontFace(gl.CCW);
		gl.blendFunc(gl.ONE, gl.ZERO);
		gl.blendEquation(gl.FUNC_ADD);
		gl.clearColor(0, 0, 0, 0);
		gl.clearDepth(1.0);
		gl.clearStencil(0);
		gl.lineWidth(1);
		gl.pixelStorei(gl.UNPACK_ALIGNMENT, 4);
		gl.pixelStorei(gl.PACK_ALIGNMENT, 4);
		try { gl.pixelStorei(gl.UNPACK_FLIP_Y_WEBGL, false); } catch (_) {}
		try { gl.pixelStorei(gl.UNPACK_PREMULTIPLY_ALPHA_WEBGL, false); } catch (_) {}
		// Unbind across all texture units the runtime exposes, not just
		// TEXTURE0. Previous tests may have bound textures to TEXTURE1+
		// and left them live, so the next test sees stale samplers.
		try {
			const maxUnits = gl.getParameter(gl.MAX_COMBINED_TEXTURE_IMAGE_UNITS) || 8;
			for (let i = 0; i < maxUnits; i++) {
				gl.activeTexture(gl.TEXTURE0 + i);
				gl.bindTexture(gl.TEXTURE_2D, null);
				gl.bindTexture(gl.TEXTURE_CUBE_MAP, null);
			}
		} catch (_) {}
		gl.activeTexture(gl.TEXTURE0);
		const w = webglCanvasShim.width, h = webglCanvasShim.height;
		gl.viewport(0, 0, w, h);
		gl.scissor(0, 0, w, h);
		drainGlErrors(gl);
	} catch (e) {
		realConsoleDebug('[runner] resetGLState threw', e);
	}
}

