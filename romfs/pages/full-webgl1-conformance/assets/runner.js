// wtu.setupIndexedQuad — quad with shared vertices + element index
// buffer. Several attrib/rendering tests need it. Returns position
// + index buffers.
globalThis.WebGLTestUtils.setupIndexedQuad = function (gl, gridRes, positionLoc) {
	positionLoc = positionLoc || 0;
	gridRes = gridRes || 1;
	const positions = [];
	const indices = [];
	for (let y = 0; y <= gridRes; y++) {
		for (let x = 0; x <= gridRes; x++) {
			positions.push(-1 + 2 * x / gridRes, -1 + 2 * y / gridRes, 0);
		}
	}
	for (let y = 0; y < gridRes; y++) {
		for (let x = 0; x < gridRes; x++) {
			const i = y * (gridRes + 1) + x;
			indices.push(i, i + 1, i + gridRes + 1,
				i + 1, i + gridRes + 2, i + gridRes + 1);
		}
	}
	const pbuf = gl.createBuffer();
	gl.bindBuffer(gl.ARRAY_BUFFER, pbuf);
	gl.bufferData(gl.ARRAY_BUFFER, new Float32Array(positions), gl.STATIC_DRAW);
	gl.enableVertexAttribArray(positionLoc);
	gl.vertexAttribPointer(positionLoc, 3, gl.FLOAT, false, 0, 0);
	const ibuf = gl.createBuffer();
	gl.bindBuffer(gl.ELEMENT_ARRAY_BUFFER, ibuf);
	gl.bufferData(gl.ELEMENT_ARRAY_BUFFER,
		new Uint16Array(indices), gl.STATIC_DRAW);
	return [pbuf, ibuf];
};

