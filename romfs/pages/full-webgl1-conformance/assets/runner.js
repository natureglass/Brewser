// Full WebGL 1 conformance runner.
//
// Loaded as `<script src="assets/runner.js">` from
// `romfs/pages/full-webgl1-conformance/index.html`. canvas-runner wraps
// our body as `new AsyncFunctionCtor('document', 'console', body)` and
// calls it with the per-page documentShim + a routed-to-debug consoleShim,
// so `document` and `console` arrive as parameters and we get top-level
// `await` for free.
//
// Architecture:
//   - Install a self-contained mini-harness (description, debug,
//     testPassed/Failed, shouldBe*, WebGLTestUtils, finishTest) on
//     `globalThis`. Mirrors the existing per-demo harness at
//     romfs/pages/threejs-demos/libs/harness.js, with a `resetHarness()`
//     hook so we can reuse it across hundreds of tests.
//   - Fetch the test list from `assets/tests.json` (generated by the
//     sync-khronos-tests script at build time from each conformance dir's
//     `00_test_list.txt`).
//   - For each test:
//       * Reset the harness counters/log.
//       * Reset GL state (drain errors, restore spec defaults on the
//         shared screen GL — see [[swb-shared-gl-state-leak]]).
//       * Fetch the test's HTML from
//         `romfs:/.../sdk/tests/conformance/<rel>`.
//       * Parse out: <canvas> tags, <script id type=x-shader> shader
//         blocks, <script src> dependencies, and inline <script> bodies.
//       * Override `document.getElementById` to serve the test's
//         canvas id + shader-block shims; fall through to the
//         canvas-runner's original shim for our own `webgl-canvas` /
//         `status`.
//       * Pre-fetch and indirect-eval each <script src> dependency we
//         don't already shim (we skip js-test-pre/post and
//         webgl-test-utils since the harness above replaces them).
//       * Indirect-eval the inline body via `(0, eval)(...)` so
//         top-level `var foo = ...` declarations become globals —
//         Khronos tests rely on this for `shouldBe('foo', ...)` to see
//         them. (AsyncFunction locals are invisible to gEval; see
//         the `khronos-conformance-harness` memory.)
//       * Wait up to 5 rAF ticks for `finishTest()` to fire (if the
//         test deferred via setTimeout chains we don't truly support
//         it'll time out — that's fine).
//       * Record the result, append per-test detail to our SDMC log,
//         update the status canvas.
//
// Failure modes documented in memory we work around:
//   - [[console-error-switches-render-mode]]: globalThis.console.log/
//     warn/error/info are no-ops by the time any Khronos code runs.
//   - [[swb-content-cache-ceiling]]: this page stays <2048 px tall.
//   - [[swb-mime-by-ext-trap]]: tests.json, .html, .js extensions are
//     all registered in browser-resource-loader.ts.
//   - [[nxjs-image-bypasses-global-fetch]]: tests that use `new Image()`
//     will fail because the romfs:/ scheme isn't recognized by nx.js's
//     module-local fetch. Failure is recorded.

