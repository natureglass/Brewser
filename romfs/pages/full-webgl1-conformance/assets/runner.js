// Monkey-patch create3DContext to add bridge-prototype enable + error
// drain. The real Khronos implementation returns a bare context; ours
// needs to opt into the GPU bridge so draws land in a readable FBO
// instead of being software-rasterized into cairo directly. Also drains
// any GL error state inherited from the previous test (the shared screen
// GL context persists across all tests — see [[swb-shared-gl-state-leak]]).
{
	const realCreate3DContext = globalThis.WebGLTestUtils.create3DContext;
	globalThis.WebGLTestUtils.create3DContext = function (elementOrId, attribs, version) {
		// Khronos's `create3DContext()` with no element auto-creates a
		// fresh <canvas>; we don't synthesize canvases, so fall back to
		// our shared `webgl-canvas` element.
		if (elementOrId === undefined || elementOrId === null) {
			elementOrId = globalThis.document.getElementById('webgl-canvas');
		}
		const gl = realCreate3DContext.call(this, elementOrId, attribs, version);
		if (gl && typeof gl.enableGpuBridgePrototype === 'function') {
			try { gl.enableGpuBridgePrototype(true); } catch (_) {}
		}
		if (gl) {
			let drains = 0;
			while (drains < 100 && gl.getError() !== gl.NO_ERROR) drains++;
		}
		return gl;
	};
	// Many tests use this thin wrapper that's supposed to throw on GL error;
	// the bare context is fine for our purposes (most assertions check
	// gl.getError directly).
	globalThis.WebGLTestUtils.create3DContextWithWrapperThatThrowsOnGLError =
		globalThis.WebGLTestUtils.create3DContext;
}

