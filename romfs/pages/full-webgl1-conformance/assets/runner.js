function gamepadState() {
	try {
		const pads = (typeof navigator !== 'undefined' && navigator.getGamepads)
			? navigator.getGamepads() : null;
		if (!pads) return null;
		const gp = pads[0];
		if (!gp) return null;
		// Standard Switch mapping: button 1 = A, button 0 = B, button 9 = +.
		return {
			A: !!(gp.buttons[1] && gp.buttons[1].pressed),
			B: !!(gp.buttons[0] && gp.buttons[0].pressed),
			PLUS: !!(gp.buttons[9] && gp.buttons[9].pressed),
		};
	} catch (_) { return null; }
}

let rafFiredCount = 0;
function nextFrame() {
	// Use setTimeout, NOT requestAnimationFrame. Routing through rAF
	// would cause the browser shell's `tickAnimationFrames()` to
	// return true each frame, which gates the shell's `repaintContent()`
	// call that blits the cached HTML content over the entire viewport
	// and clobbers our direct draws to `Switch.screen`. With setTimeout
	// the shell sees no rAF activity → no repaintContent → our screen
	// writes persist between frames. Each main-loop iteration drains
	// timers, so this still paces at ~one tick / frame.
	return new Promise((resolve) => {
		setTimeout(() => {
			rafFiredCount++;
			resolve(typeof performance !== 'undefined' && performance.now
				? performance.now() : Date.now());
		}, 0);
	});
}

// Independent UI heartbeat. Even if main() is blocked, this fires on
// every rAF tick the shell drains and updates the status canvas with
// the latest rAF count + diagnostic counters. If rAF itself is broken,
// the count stays at 0 — telling us where to look. Also writes a diag
// entry every 60 ticks (~1 sec at 60fps) so we can verify rAF liveness
// independent of main's progress in the diag log.
let heartbeatTickCount = 0;
// nx.js's font subsystem reloads the FreeType face on every
// `ctx.font = ...` assignment. After enough cumulative assignments the
// file-handle pool exhausts and the load fails with "FreeType: failed
// to load font face (error 6)". Mitigated two ways:
//   1. renderStatus() now uses a SINGLE font for the whole render
//      (was 6 different sizes/weights → 1, cutting load rate by 6×).
//   2. heartbeat throttles renderStatus to ~5fps instead of 60fps
//      (further 12× reduction).
// Even with those mitigations, prolonged runs may eventually exhaust.
// `safeRenderStatus` now PERIODICALLY RETRIES after marking broken,
// because the failure may be transient (file descriptors free up) and
// we want the UI to recover instead of staying frozen forever.
let renderStatusBroken = false;
let renderStatusBrokenTick = 0;
let renderStatusRetryEvery = 60; // try again every ~60 heartbeat ticks (~12s at 5fps)
function safeRenderStatus(callerLabel) {
	if (renderStatusBroken) {
		// Try again periodically — if FreeType has recovered we resume.
		if (heartbeatTickCount - renderStatusBrokenTick < renderStatusRetryEvery) {
			return false;
		}
	}
	try {
		renderStatus();
		if (renderStatusBroken) {
			diag('renderStatus RECOVERED at ' + callerLabel +
				' tick ' + heartbeatTickCount);
			renderStatusBroken = false;
		}
		return true;
	} catch (e) {
		if (!renderStatusBroken) {
			diag('renderStatus BROKEN at ' + callerLabel +
				' tick ' + heartbeatTickCount + ': ' +
				(e && e.message ? e.message : e));
		}
		renderStatusBroken = true;
		renderStatusBrokenTick = heartbeatTickCount;
		// Back off the retry interval each consecutive failure, up to ~60s,
		// so we don't burn cycles re-failing while resources are scarce.
		renderStatusRetryEvery = Math.min(360, renderStatusRetryEvery * 2);
		return false;
	}
}
// Repaint the UI every heartbeat tick. The legacy 12-tick throttle existed
// because each ctx.font assignment used to leak a fresh ~2 MB system-font
// allocation in nx.js's FontFaceSet — see [[nxjs-font-no-bold-italic]] for
// the 2026-05-23 idempotency fix that closed that leak. With the leak gone
// renderStatus is essentially free, and painting every tick is desirable
// now that the UI draws to Switch.screen directly: the browser shell's
// chrome strip is repainted at the shell's tick rate on top of our writes,
// so a slower runner repaint would let the chrome flicker over the top
// rows of our UI between paints.
function heartbeat() {
	activeHeartbeatTimerId = 0; // current timer has fired
	if (!runnerActive) return; // page is navigating away — stop the chain
	heartbeatTickCount++;
	UI.rafFiredCount = rafFiredCount;
	UI.heartbeatTickCount = heartbeatTickCount;
	safeRenderStatus('heartbeat');
	// Atomic blit of the offscreen UI frame to the screen. Single
	// drawImage call overwrites the whole screen rect with this frame's
	// pixels — no possibility of prior-frame text bleeding through. Skip
	// if statusCanvas IS the screen (fallback path when OffscreenCanvas
	// creation failed) since drawImage(self, self) would be a no-op +
	// possibly invalid.
	if (screenCtx && statusCanvas && statusCanvas !== screenCanvas) {
		try {
			screenCtx.drawImage(statusCanvas, 0, 0);
		} catch (_) { /* swallow per-frame; if persistent we'd see no UI */ }
	}
	if (heartbeatTickCount === 1 || heartbeatTickCount % 60 === 0) {
		diag('heartbeat tick #' + heartbeatTickCount +
			' rafFiredCount=' + rafFiredCount +
			(renderStatusBroken ? ' [renderStatus broken, retry in ' +
				(renderStatusRetryEvery - (heartbeatTickCount - renderStatusBrokenTick)) +
				' ticks]' : ''));
	}
	// setTimeout, not requestAnimationFrame — see nextFrame() comment.
	// Driving the heartbeat through rAF would mark the page as animated
	// and trigger the shell's per-tick repaintContent cache-blit, which
	// clobbers our direct draws to Switch.screen.
	activeHeartbeatTimerId = setTimeout(heartbeat, 16);
}

async function waitForStart(timeoutMs) {
	UI.state = 'waiting-start';
	const start = Date.now();
	let prev = null;
	let iters = 0;
	while (Date.now() - start < timeoutMs) {
		UI.startCountdown = Math.max(0, Math.ceil((timeoutMs - (Date.now() - start)) / 1000));
		safeRenderStatus('waitForStart-iter-' + iters);
		await nextFrame();
		iters++;
		if (iters === 1 || iters % 30 === 0) {
			diag('  waitForStart iter ' + iters +
				' elapsed=' + (Date.now() - start) + 'ms');
		}
		const cur = gamepadState();
		if (cur && cur.A && !(prev && prev.A)) return 'manual';
		prev = cur;
	}
	return 'auto';
}

