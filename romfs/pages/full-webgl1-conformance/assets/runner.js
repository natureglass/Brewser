// the status canvas is blank for the first frame, then populates one
// tick later.
UI.state = 'idle';
UI.currentName = '(loading test list…)';
safeRenderStatus('initial');
diag('initial renderStatus done');

// Start independent UI heartbeat — fires on every rAF tick and updates
// the status canvas regardless of whether main() is making progress.
// If rAF is broken, the rAF-fired counter shown in the UI stays at 0
// and we know to investigate the tick chain itself.
heartbeat();
diag('heartbeat scheduled (setTimeout-driven, not rAF — see nextFrame)');

// CRITICAL: do NOT `await main()` here. The browser shell awaits
// runPageScripts() before laying out and painting the page (see
// browser-shell.ts ~line 183). Our main() loops over hundreds of tests
// and never returns, so `await`ing it here would block the very first
// page paint — the page would appear stuck on whatever the previous
// frame had, no status canvas updates ever visible. Fire as a detached
// promise: the script body returns immediately, the shell completes
// layout + paint, and main() then continues to drive itself via the
// rAF tick the shell drains every frame.
main().catch((e) => {
	realConsoleDebug('[runner] top-level main threw', e);
	UI.state = 'aborted';
	UI.currentName = 'runner crashed: ' + (e && e.message ? e.message : e);
	try { renderStatus(); } catch (_) {}
});
diag('main() fired (detached); script body returning');
