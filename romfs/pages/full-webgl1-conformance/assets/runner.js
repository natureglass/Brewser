function normalizeUrl(url) {
	const m = /^([a-z][a-z0-9+.-]*:\/{0,3})(.*)$/i.exec(url);
	if (!m) return url;
	const scheme = m[1];
	const path = m[2];
	const segs = path.split('/');
	const out = [];
	for (const seg of segs) {
		if (seg === '.') continue;
		if (seg === '..') { if (out.length > 0 && out[out.length - 1] !== '') out.pop(); continue; }
		out.push(seg);
	}
	return scheme + out.join('/');
}

function resolveUrl(src, base) {
	if (/^[a-z][a-z0-9+.-]*:/i.test(src)) return src;
	if (!base) return src;
	if (src.startsWith('/')) {
		const m = /^([a-z][a-z0-9+.-]*:\/{0,3}[^/]*)/i.exec(base);
		return (m ? m[1] : '') + src;
	}
	const lastSlash = base.lastIndexOf('/');
	const baseDir = lastSlash >= 0 ? base.slice(0, lastSlash + 1) : '';
	return normalizeUrl(baseDir + src);
}

